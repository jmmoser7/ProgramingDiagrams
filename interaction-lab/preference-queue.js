'use strict';
// This worker applies data-only lab parameters. It never evaluates feedback or
// edits the Program board, Pack, or ISO tools.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const {execFile} = require('node:child_process');
const runFile = require('node:util').promisify(execFile);
const Catalog = require('./catalog.js');
const Model = require('./model.js');
const acceptedPrefix = '/* Generated by the local interaction preference worker. Data only. */\n(function(root,factory){const data=factory();if(typeof module===\'object\'&&module.exports)module.exports=data;else root.InteractionAcceptedPreferences=data;})(typeof window===\'object\'?window:globalThis,function(){return ';
const acceptedSuffix = ';});\n';
const forbidden = new Set(['__proto__', 'constructor', 'prototype']);
const clone = value => JSON.parse(JSON.stringify(value));
const object = value => value && typeof value === 'object' && !Array.isArray(value);
function canonical(value) {
  if (Array.isArray(value)) return '[' + value.map(canonical).join(',') + ']';
  if (object(value)) return '{' + Object.keys(value).sort().map(key => JSON.stringify(key) + ':' + canonical(value[key])).join(',') + '}';
  return JSON.stringify(value);
}
function fingerprint(value) { return crypto.createHash('sha256').update(canonical(value)).digest('hex'); }
function problem(message, statusCode = 400) { return Object.assign(new Error(message), {statusCode}); }
function validWorkspace(workspaceId) {
  if (typeof workspaceId !== 'string' || !/^[A-Za-z0-9][A-Za-z0-9._:-]{0,159}$/.test(workspaceId) || forbidden.has(workspaceId)) throw problem('A valid workspaceId is required.');
  return workspaceId;
}
function validateFeedback(raw = []) {
  if (!Array.isArray(raw) || raw.length > 2000) throw problem('Feedback must contain at most 2000 observations.');
  const ids = new Set();
  return raw.map(item => {
    if (!object(item) || typeof item.id !== 'string' || !/^[A-Za-z0-9][A-Za-z0-9._:-]{0,159}$/.test(item.id) || forbidden.has(item.id) || ids.has(item.id)) throw problem('Feedback requires unique safe observation IDs.');
    if (typeof item.text !== 'string' || !item.text.trim() || !['Needs tuning', 'Feels right', 'Needs native comparison'].includes(item.verdict) || !['saved', 'draft'].includes(item.source)) throw problem('Invalid feedback observation.');
    ids.add(item.id);
    return {id: item.id, text: item.text.trim().slice(0, 20000), verdict: item.verdict, source: item.source};
  });
}
function readFeedbackResolutions(file) {
  if (!fs.existsSync(file)) return {entries: [], error: null};
  try {
    const data = JSON.parse(fs.readFileSync(file, 'utf8'));
    if (!object(data) || data.version !== 1 || !Array.isArray(data.entries) || data.entries.length > 20000) throw new Error('Expected version 1 and an entries array.');
    const entries = [];
    for (const item of data.entries) {
      if (!object(item) || !Catalog.cases.some(study => study.id === item.caseId) || typeof item.feedbackHash !== 'string' || !/^[a-f0-9]{64}$/i.test(item.feedbackHash)) continue;
      const texts = values => Array.isArray(values) && values.length > 0 && values.length <= 200 && values.every(value => typeof value === 'string' && value.trim() && value.length <= 2000);
      if (typeof item.summary !== 'string' || !item.summary.trim() || item.summary.length > 20000 || !texts(item.files) || !texts(item.checks) || typeof item.implementedAt !== 'string' || !Number.isFinite(Date.parse(item.implementedAt))) continue;
      entries.push({caseId: item.caseId, feedbackHash: item.feedbackHash.toLowerCase(), summary: item.summary.trim(), files: item.files.map(value => value.trim()), checks: item.checks.map(value => value.trim()), implementedAt: new Date(item.implementedAt).toISOString()});
    }
    return {entries, error: entries.length === data.entries.length ? null : 'Some feedback receipts were ignored because implementation evidence was incomplete.'};
  } catch (error) { return {entries: [], error: 'Feedback receipts could not be read: ' + error.message}; }
}
function validateSnapshot(caseId, snapshot, revision = 1, savedAt = new Date().toISOString()) {
  const study = Catalog.cases.find(item => item.id === caseId);
  if (!study) throw problem('Unknown interaction prototype: ' + caseId + '.');
  if (!object(snapshot) || !object(snapshot.settings)) throw problem('A prototype settings snapshot is required.');
  if (!Number.isSafeInteger(revision) || revision < 1) throw problem('Commit revision must be a positive integer.');
  if (typeof savedAt !== 'string' || !Number.isFinite(Date.parse(savedAt))) throw problem('Commit savedAt must be a valid date.');
  if (Object.keys(snapshot).some(key => !['settings', 'groups', 'objects', 'geometry'].includes(key))) throw problem('Unsupported prototype snapshot property.');
  const keys = new Set(Catalog.keysFor(study));
  const checkBucket = bucket => {
    if (!object(bucket)) throw problem('Prototype settings must be an object.');
    for (const [key, value] of Object.entries(bucket)) {
      const field = Catalog.fields[key];
      if (forbidden.has(key) || !field || !keys.has(key) || field.section === 'Geometry') throw problem('Unsupported prototype setting: ' + key + '.');
      if (field.type === 'number' && (typeof value !== 'number' || !Number.isFinite(value) || value < field.min || value > field.max)) throw problem('Out-of-range setting: ' + key + '.');
      if (field.type === 'boolean' && typeof value !== 'boolean') throw problem('Invalid boolean setting: ' + key + '.');
      if (field.type === 'color' && (typeof value !== 'string' || !/^#[0-9a-f]{6}$/i.test(value))) throw problem('Invalid color setting: ' + key + '.');
      if (field.type === 'enum' && !field.options.includes(value)) throw problem('Unsupported cursor or presentation setting: ' + key + '.');
    }
  };
  checkBucket(snapshot.settings);
  for (const store of ['groups', 'objects']) {
    if (snapshot[store] === undefined) continue;
    if (!object(snapshot[store]) || Object.keys(snapshot[store]).length > 500) throw problem('Invalid prototype ' + store + '.');
    for (const [id, values] of Object.entries(snapshot[store])) {
      if (!id || id.length > 160 || forbidden.has(id)) throw problem('Invalid prototype ' + store + ' ID.');
      checkBucket(values);
    }
  }
  let state;
  try { state = Model.validate({version: 1, commits: {[caseId]: {snapshot, revision, savedAt}}}); }
  catch (error) { throw problem(error.message); }
  const clean = state.commits?.[caseId];
  if (!clean) throw problem('The preference model rejected this commit.');
  return clone(clean);
}
function acceptedSource(data) { return acceptedPrefix + JSON.stringify(data, null, 2).replace(/</g, '\\u003c').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029') + acceptedSuffix; }
function readAccepted(file) {
  if (!fs.existsSync(file)) return {version: 1, cases: {}, updatedAt: null};
  const source = fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
  if (!source.startsWith(acceptedPrefix) || !source.endsWith(acceptedSuffix)) throw new Error('Accepted preference file has an unsupported format.');
  const data = JSON.parse(source.slice(acceptedPrefix.length, -acceptedSuffix.length));
  if (data.version !== 1 || !object(data.cases)) throw new Error('Invalid accepted preference file.');
  for (const [caseId, snapshot] of Object.entries(data.cases)) data.cases[caseId] = validateSnapshot(caseId, snapshot).snapshot;
  return data;
}
async function atomicWrite(file, contents) {
  await fs.promises.mkdir(path.dirname(file), {recursive: true});
  const temp = file + '.' + crypto.randomUUID() + '.tmp';
  try { await fs.promises.writeFile(temp, contents, {encoding: 'utf8', flag: 'wx'}); await fs.promises.rename(temp, file); }
  finally { await fs.promises.unlink(temp).catch(() => {}); }
}

// Exercise the real scene engine with each candidate's settings and geometry.
function validateRuntimeCandidate(candidate) {
  const Stage = require('./stage.js');
  class Element {
    constructor(ownerDocument) { this.ownerDocument = ownerDocument; this.style = {}; this.children = []; this.listeners = {}; this.value = ''; }
    addEventListener(type, fn) { (this.listeners[type] ||= []).push(fn); }
    removeEventListener(type, fn) { this.listeners[type] = (this.listeners[type] || []).filter(item => item !== fn); }
    appendChild(child) { this.children.push(child); child.parentElement = this; }
    remove() { if (this.parentElement) this.parentElement.children = this.parentElement.children.filter(child => child !== this); }
    setAttribute() {}
    focus() { this.ownerDocument.activeElement = this; }
    getBoundingClientRect() { return {left: 0, top: 0, width: 800, height: 500}; }
  }
  const previous = Object.fromEntries(['requestAnimationFrame', 'cancelAnimationFrame', 'ResizeObserver'].map(key => [key, global[key]]));
  const frames = new Map(); let frameId = 0;
  global.requestAnimationFrame = fn => { const id = ++frameId; frames.set(id, fn); return id; };
  global.cancelAnimationFrame = id => frames.delete(id);
  global.ResizeObserver = class { observe() {} disconnect() {} };
  try {
    for (const [caseId, raw] of Object.entries(candidate.cases)) {
      const snapshot = validateSnapshot(caseId, raw).snapshot;
      const study = Catalog.cases.find(item => item.id === caseId);
      const document = new Element(); document.ownerDocument = document; document.createElement = () => new Element(document); document.body = new Element(document);
      const canvas = new Element(document), overlay = new Element(document); overlay.appendChild(canvas);
      const context = new Proxy({measureText: text => ({width: String(text).length * 6})}, {get: (target, key) => key in target ? target[key] : () => {}});
      canvas.getContext = () => context;
      const stage = Stage.create({canvas, overlay, settings: snapshot.settings, caseStudy: study, resolveSettings: item => ({...snapshot.settings, ...snapshot.groups[item.group], ...snapshot.objects[item.id]})});
      try {
        if (snapshot.geometry !== null) stage.restore({version: 1, objects: snapshot.geometry});
        const pending = [...frames.values()]; frames.clear(); pending.forEach(fn => fn(performance.now()));
        const scene = Model.cleanScene(stage.serialize());
        if (snapshot.geometry !== null && scene.objects.length !== snapshot.geometry.length) throw new Error('Runtime geometry did not match the accepted snapshot.');
      } finally { stage.destroy(); frames.clear(); }
    }
  } finally { for (const [key, value] of Object.entries(previous)) if (value === undefined) delete global[key]; else global[key] = value; }
}
async function validateCandidateInChild(candidate, options) {
  const file = path.join(options.queueDir, 'candidate-' + crypto.randomUUID() + '.json');
  await atomicWrite(file, JSON.stringify(candidate));
  const config = {cwd: options.rootDir, windowsHide: true, timeout: 120000, maxBuffer: 2 * 1024 * 1024};
  try {
    await runFile(process.execPath, [__filename, '--validate-candidate', file], config);
    for(const suite of ['test-interaction-lab.js','interaction-lab/test-lab-stage.js','interaction-lab/test-component-marquee.js','interaction-lab/test-direction-constraint.js','test-tracking-guides.js','interaction-lab/test-precision-stage.js'])await runFile(process.execPath,[suite],config);
  } catch (error) { throw new Error('Prototype validation failed: ' + String(error.stderr || error.stdout || error.message).trim().slice(-2500)); }
  finally { await fs.promises.unlink(file).catch(() => {}); }
}

function createPreferenceQueue(config = {}) {
  const rootDir = path.resolve(config.rootDir || path.join(__dirname, '..'));
  const options = {rootDir, queueDir: path.resolve(config.queueDir || path.join(rootDir, '.local', 'interaction-preferences')), acceptedFile: path.resolve(config.acceptedFile || path.join(rootDir, 'interaction-lab', 'accepted-preferences.js')), resolutionsFile: path.resolve(config.resolutionsFile || path.join(rootDir, 'interaction-lab', 'feedback-resolutions.json'))};
  const queueFile = path.join(options.queueDir, 'queue.json');
  let jobs = [], running = false, scheduled = false, closed = false, fatalError = null, chain = Promise.resolve();
  const lock = fn => { const result = chain.then(fn); chain = result.catch(() => {}); return result; };
  const now = () => new Date().toISOString();
  const persist = () => atomicWrite(queueFile, JSON.stringify({version: 1, jobs}, null, 2));
  const publicJob = (job, resolutions) => {
    const result = Object.fromEntries(Object.entries(job).filter(([key]) => !['snapshot', 'workspaceId', 'feedback', 'addressedAt'].includes(key)));
    const successful = job.status === 'applied';
    result.feedback = job.feedback.map(item => {
      const hash = fingerprint(item), resolution = resolutions.find(entry => entry.caseId === job.caseId && entry.feedbackHash === hash);
      return {...item, hash, status: successful && resolution ? 'addressed' : 'pending', ...(successful && resolution ? {resolution} : {})};
    });
    if (successful) {
      if (result.feedback.length && result.feedback.every(item => item.status === 'addressed')) {
        result.status = 'addressed'; result.message = 'Prototype settings applied; every submitted comment has matching implementation evidence.';
        result.addressedAt = result.feedback.map(item => item.resolution.implementedAt).sort().at(-1);
      } else if (result.feedback.length) {
        result.status = 'needs-review'; result.message = 'Prototype settings applied. Written feedback is awaiting implementation review.';
      } else { result.status = 'applied'; result.message = 'Prototype settings applied and verified. No written feedback was submitted with this revision.'; }
    }
    return result;
  };
  const latestFor = (workspaceId, caseId) => jobs.filter(job => job.workspaceId === workspaceId && job.caseId === caseId && job.status !== 'superseded').at(-1);
  const status = workspaceId => {
    validWorkspace(workspaceId);
    const resolutions = readFeedbackResolutions(options.resolutionsFile);
    return {worker: {mode: 'local', scope: 'interaction-lab', running, queued: jobs.filter(job => job.workspaceId === workspaceId && job.status === 'queued').length, error: fatalError, feedbackError: resolutions.error}, jobs: jobs.filter(job => job.workspaceId === workspaceId).map(job => publicJob(job, resolutions.entries)), feedbackResolutions: resolutions.entries};
  };
  try {
    if (fs.existsSync(queueFile)) {
      const saved = JSON.parse(fs.readFileSync(queueFile, 'utf8'));
      if (saved.version !== 1 || !Array.isArray(saved.jobs) || saved.jobs.length > 20000) throw new Error('Invalid persisted preference queue.');
      jobs = saved.jobs.map(job => {
        validWorkspace(job.workspaceId);
        if (!['queued', 'working', 'applied', 'needs-review', 'addressed', 'failed', 'superseded'].includes(job.status)) throw new Error('Invalid persisted job status.');
        const feedback = validateFeedback(job.feedback), feedbackHash = fingerprint(feedback), persistedHash = fingerprint(job.snapshot);
        const persistedId = fingerprint([job.workspaceId, job.caseId, job.revision, persistedHash, feedbackHash]);
        const legacy = job.feedback === undefined && job.feedbackFingerprint === undefined && job.id === fingerprint([job.workspaceId, job.caseId, job.revision, persistedHash]);
        // Verify the exact persisted data before a newer catalog adds defaults.
        // Normalizing first would reject authentic jobs whenever a field is added.
        if ((!legacy && (job.id !== persistedId || job.feedbackFingerprint !== feedbackHash)) || job.fingerprint !== persistedHash) throw new Error('Persisted preference job identity mismatch.');
        const clean = validateSnapshot(job.caseId, job.snapshot, job.revision, job.commitSavedAt);
        const hash = fingerprint(clean.snapshot), id = fingerprint([job.workspaceId, job.caseId, job.revision, hash, feedbackHash]);
        const restored = {...job, id, fingerprint: hash, snapshot: clean.snapshot, feedback, feedbackFingerprint: feedbackHash};
        if (['addressed', 'needs-review'].includes(restored.status)) { restored.status = 'applied'; restored.appliedAt ||= restored.addressedAt || restored.updatedAt; delete restored.addressedAt; restored.message = 'Prototype settings applied; feedback completion requires matching implementation evidence.'; }
        if (restored.status === 'working') Object.assign(restored, {status: 'queued', message: 'Resuming validation after the local server restarted.', updatedAt: now()});
        return restored;
      });
    }
  } catch (error) { fatalError = 'Preference queue could not be restored: ' + error.message; jobs = []; }
  const validateCandidate = config.validateCandidate || (candidate => validateCandidateInChild(candidate, options));
  function wake() {
    if (running || scheduled || closed || fatalError) return;
    scheduled = true;
    setImmediate(() => { scheduled = false; if (!closed) processJobs().catch(error => { fatalError = error.message; }); });
  }
  async function processJobs() {
    if (running || closed || fatalError) return;
    running = true;
    try {
      while (!closed) {
        const job = await lock(async () => {
          const next = jobs.find(item => item.status === 'queued');
          if (!next) return null;
          next.status = 'working'; next.message = 'Checking prototype parameters and scene behavior.'; next.updatedAt = now(); await persist(); return clone(next);
        });
        if (!job) break;
        try {
          const candidate = readAccepted(options.acceptedFile);
          candidate.cases[job.caseId] = validateSnapshot(job.caseId, job.snapshot, job.revision, job.commitSavedAt).snapshot;
          candidate.updatedAt = now();
          await validateCandidate(clone(candidate));
          await lock(async () => {
            const current = jobs.find(item => item.id === job.id);
            if (current.status === 'superseded') return;
            // The latest-commit check and publishing share the mutation lock.
            if (latestFor(job.workspaceId, job.caseId)?.id !== job.id) { current.status = 'superseded'; current.message = 'A newer commit replaced this preference.'; }
            else {
              await atomicWrite(options.acceptedFile, acceptedSource(candidate));
              current.status = 'applied'; current.message = 'Applied prototype settings; scene and regression checks passed. Written feedback requires implementation review.'; current.appliedAt = now();
            }
            current.updatedAt = now(); await persist();
          });
        } catch (error) {
          await lock(async () => {
            const current = jobs.find(item => item.id === job.id);
            if (current.status !== 'superseded') { current.status = 'failed'; current.message = String(error.message).slice(0, 3000); current.updatedAt = now(); }
            await persist();
          });
        }
      }
    } finally { running = false; if (!closed && jobs.some(job => job.status === 'queued')) wake(); }
  }
  async function enqueue(payload) {
    if (closed) throw problem('The local preference worker has stopped.', 503);
    if (fatalError) throw problem(fatalError, 503);
    if (!object(payload)) throw problem('A commit request is required.');
    const workspaceId = validWorkspace(payload.workspaceId);
    if (!object(payload.commits) || !Object.keys(payload.commits).length || Object.keys(payload.commits).length > Catalog.cases.length) throw problem('Choose at least one known prototype to commit.');
    // Validate the complete batch before adding any job.
    const incoming = Object.entries(payload.commits).map(([caseId, raw]) => {
      if (!object(raw)) throw problem('Invalid prototype commit.');
      const clean = validateSnapshot(caseId, raw.snapshot, raw.revision, raw.savedAt), hash = fingerprint(clean.snapshot), feedback = validateFeedback(raw.feedback), feedbackHash = fingerprint(feedback);
      return {id: fingerprint([workspaceId, caseId, clean.revision, hash, feedbackHash]), workspaceId, caseId, snapshot: clean.snapshot, fingerprint: hash, feedback, feedbackFingerprint: feedbackHash, revision: clean.revision, commitSavedAt: clean.savedAt};
    });
    await lock(async () => {
      if (jobs.length + incoming.filter(item => !jobs.some(job => job.id === item.id)).length > 20000) throw problem('Preference history is full; archive the local queue before adding more commits.', 503);
      const before = clone(jobs);
      try {
        for (const item of incoming) {
          if (jobs.some(job => job.id === item.id)) continue;
          const latest = latestFor(workspaceId, item.caseId), stale = latest && item.revision < latest.revision;
          if (!stale) for (const previous of jobs) if (previous.workspaceId === workspaceId && previous.caseId === item.caseId && ['queued', 'working'].includes(previous.status)) { previous.status = 'superseded'; previous.message = 'A newer commit replaced this preference.'; previous.updatedAt = now(); }
          const timestamp = now();
          jobs.push({...item, status: stale ? 'superseded' : 'queued', message: stale ? 'This revision is older than the latest committed preference.' : 'Waiting for local prototype validation.', createdAt: timestamp, updatedAt: timestamp});
        }
        await persist();
      } catch (error) { jobs = before; throw error; }
    });
    wake(); return status(workspaceId);
  }
  const ready = fatalError ? Promise.resolve() : lock(async () => { if (jobs.length) await persist(); }).then(wake).catch(error => { fatalError = 'Preference queue could not start: ' + error.message; });
  return {enqueue, status, ready, close() { closed = true; }, async idle() { await ready; do { await new Promise(resolve => setTimeout(resolve, 10)); await chain; } while (running || scheduled); }, paths: {...options, queueFile}};
}
module.exports = {createPreferenceQueue, validateSnapshot, validateFeedback, readFeedbackResolutions, validateRuntimeCandidate, acceptedSource, readAccepted, fingerprint};
if (require.main === module && process.argv[2] === '--validate-candidate') {
  try {
    const candidate = JSON.parse(fs.readFileSync(process.argv[3], 'utf8'));
    if (candidate.version !== 1 || !object(candidate.cases)) throw new Error('Invalid candidate preferences.');
    validateRuntimeCandidate(candidate); process.stdout.write('Candidate prototype scene checks passed.\n');
  } catch (error) { process.stderr.write(error.stack + '\n'); process.exitCode = 1; }
}
